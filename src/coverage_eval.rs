//! Explicit evaluation of a trusted target checkout; never builds or activates.
use crate::{
    coverage,
    desktop::DesktopKind,
    inventory::Inventory,
    manjaro,
    mapping::{self, Decision, ReviewedMappings, Status},
    output,
};
use serde::{Deserialize, Serialize};
use std::{
    collections::{BTreeMap, BTreeSet},
    fs,
    path::Path,
};

const PROVIDER: &str = "evaluated target system packages";

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Evidence {
    pub schema_version: u32,
    pub nixpkgs_revision: String,
    pub system: String,
    pub matched: BTreeMap<String, MatchEvidence>,
    pub candidate_count: usize,
    pub unavailable_candidates: usize,
    pub unavailable_system_packages: usize,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct MatchEvidence {
    pub path: String,
    pub outputs: Vec<String>,
    pub priority: i64,
}

// The input module files are generated by nixify in a fresh private directory;
// packages.nix is empty. Output paths compare derivation outputs, not pnames.
const EXPRESSION: &str = r#"{ nixpkgsPath, projectPath, system, attributesPath }:
let
  nixpkgs = builtins.toPath nixpkgsPath;
  project = builtins.toPath projectPath;
  evaluated = import (nixpkgs + "/nixos/lib/eval-config.nix") {
    inherit system;
    modules = [ (project + "/configuration.nix") ({ lib, ... }: {
      system.stateVersion = lib.mkDefault "24.11";
      boot.loader.grub.devices = lib.mkDefault [ "nodev" ];
      fileSystems."/" = { device = lib.mkDefault "/dev/null"; fsType = lib.mkDefault "ext4"; };
    }) ];
  };
  pkgs = evaluated.pkgs;
  attrs = builtins.fromJSON (builtins.readFile (builtins.toPath attributesPath));
  signature = p:
    let
      mainOutputs = if (!(p ? outputSpecified) || !p.outputSpecified) && (p.meta.outputsToInstall or null) != null
        then map (n: p.${n}.outPath) p.meta.outputsToInstall else [ p.outPath ];
      extras = builtins.filter (x: x != null) (map (n: if builtins.hasAttr n p then p.${n}.outPath else null) evaluated.config.environment.extraOutputsToInstall);
    in { path = p.outPath; outputs = mainOutputs ++ extras; priority = p.meta.priority or pkgs.lib.meta.defaultPriority; };
  attempt = p: builtins.tryEval (let s = signature p; in builtins.deepSeq s s);
  attemptedSystem = map attempt evaluated.config.environment.systemPackages;
  paths = map (x: x.value) (builtins.filter (x: x.success) attemptedSystem);
  one = attr:
    let attempted = builtins.tryEval (let p = pkgs.lib.attrByPath (pkgs.lib.splitString "." attr) null pkgs; s = if builtins.isAttrs p && p ? outPath then signature p else null; in builtins.deepSeq s s);
    in { name = attr; value = if !attempted.success || attempted.value == null then { state = "unavailable"; evidence = null; }
       else if builtins.elem attempted.value paths then { state = "matched"; evidence = attempted.value; }
       else { state = "not_matched"; evidence = null; }; };
  failures = builtins.filter (a: !a.assertion) evaluated.config.assertions;
in {
  results = builtins.listToAttrs (map one attrs);
  unavailable_system_packages = builtins.length (builtins.filter (x: !x.success) attemptedSystem);
  failed_assertions = map (a: a.message) failures;
}
"#;

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Evaluation {
    results: BTreeMap<String, Candidate>,
    unavailable_system_packages: usize,
    failed_assertions: Vec<String>,
}
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Candidate {
    state: String,
    evidence: Option<MatchEvidence>,
}

pub fn validate(
    e: &Evidence,
    revision: &str,
    system: &str,
    decisions: &[Decision],
) -> Result<(), String> {
    if e.schema_version != 1
        || e.nixpkgs_revision != revision
        || e.system != system
        || e.matched.len() > e.candidate_count
        || e.candidate_count > decisions.len()
        || e.unavailable_candidates > e.candidate_count.saturating_sub(e.matched.len())
    {
        return Err("invalid or mismatched evaluated coverage metadata".into());
    }
    let attrs: BTreeSet<_> = decisions
        .iter()
        .filter_map(|d| d.nixpkgs_attribute.as_deref())
        .collect();
    if e.candidate_count != attrs.len() {
        return Err("evaluated coverage candidate count does not match package decisions".into());
    }
    for (attr, matched) in &e.matched {
        if !attrs.contains(attr.as_str())
            || !mapping::valid_attribute(attr)
            || !valid_store_path(&matched.path)
            || matched.outputs.len() > 64
            || matched.outputs.iter().any(|path| !valid_store_path(path))
        {
            return Err("invalid evaluated coverage attribute or store path".into());
        }
    }
    Ok(())
}
fn valid_store_path(path: &str) -> bool {
    path.strip_prefix("/nix/store/").is_some_and(|name| {
        name.is_ascii()
            && name.len() > 33
            && name.len() <= 255
            && name.as_bytes()[32] == b'-'
            && name[..32]
                .bytes()
                .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit())
            && name
                .bytes()
                .all(|b| b.is_ascii_alphanumeric() || b"+._?=-".contains(&b))
    })
}

pub fn apply(
    inventory: &Inventory,
    decisions: &mut [Decision],
    e: &Evidence,
    revision: &str,
) -> Result<(), String> {
    let system = system(inventory)?;
    validate(e, revision, system, decisions)?;
    for d in decisions {
        let foreign = inventory
            .packages
            .iter()
            .find(|p| p.name == d.package)
            .is_none_or(|p| p.foreign);
        if foreign || d.status == Status::Reviewed || d.covered_by.is_some() {
            continue;
        }
        if d.nixpkgs_attribute
            .as_ref()
            .is_some_and(|a| e.matched.contains_key(a))
        {
            d.covered_by = Some(coverage::Coverage {
                provider: PROVIDER.into(),
                nixpkgs_revision: revision.into(),
            });
        }
    }
    Ok(())
}
fn system(inventory: &Inventory) -> Result<&'static str, String> {
    match inventory.source.architecture.as_str() {
        "x86_64" => Ok("x86_64-linux"),
        "aarch64" => Ok("aarch64-linux"),
        _ => Err("unsupported target architecture for evaluated coverage".into()),
    }
}

pub fn evaluate(
    inventory: &Inventory,
    revision: &str,
    review: &ReviewedMappings,
    desktop: Option<DesktopKind>,
    inspections: &[crate::config_inspection::Inspection],
    nixpkgs: &Path,
) -> Result<Evidence, String> {
    evaluate_with(
        inventory,
        revision,
        review,
        desktop,
        inspections,
        nixpkgs,
        |args| manjaro::run_bounded("nix-instantiate", args, false).map_err(|e| e.to_string()),
    )
}

pub fn evaluate_with<F>(
    inventory: &Inventory,
    revision: &str,
    review: &ReviewedMappings,
    desktop: Option<DesktopKind>,
    inspections: &[crate::config_inspection::Inspection],
    nixpkgs: &Path,
    run: F,
) -> Result<Evidence, String>
where
    F: FnOnce(&[&str]) -> Result<String, String>,
{
    let checkout =
        fs::canonicalize(nixpkgs).map_err(|e| format!("cannot access Nixpkgs checkout: {e}"))?;
    let revision_path = checkout.join(".git-revision");
    let metadata = fs::symlink_metadata(&revision_path).map_err(|_| {
        "Nixpkgs checkout needs a .git-revision matching the target; metadata is self-reported"
    })?;
    if !metadata.file_type().is_file() || metadata.len() > 1024 {
        return Err("Nixpkgs .git-revision must be a regular non-symlink file under 1 KiB".into());
    }
    let declared = fs::read_to_string(&revision_path).map_err(|_| {
        "Nixpkgs checkout needs a .git-revision matching the target; metadata is self-reported"
    })?;
    if declared.trim() != revision {
        return Err("Nixpkgs checkout .git-revision does not match target revision".into());
    }
    let checkout = checkout
        .to_str()
        .ok_or("Nixpkgs checkout path must be valid UTF-8")?;
    let system = system(inventory)?;
    let decisions = mapping::reviewed_decisions(inventory, review, Some(revision))?;
    let attrs: BTreeSet<_> = decisions
        .iter()
        .filter_map(|d| d.nixpkgs_attribute.clone())
        .collect();
    let temp = tempfile::Builder::new()
        .prefix("nixify-coverage-")
        .tempdir()
        .map_err(|e| e.to_string())?;
    let project = temp.path().join("project");
    output::generate_with_inspections(inventory, &project, revision, review, desktop, inspections)
        .map_err(|e| e.to_string())?;
    fs::write(project.join("packages.nix"), output::packages_nix(&[]))
        .map_err(|e| e.to_string())?;
    let attrs_path = temp.path().join("attributes.json");
    fs::write(
        &attrs_path,
        serde_json::to_vec(&attrs).map_err(|e| e.to_string())?,
    )
    .map_err(|e| e.to_string())?;
    let project = project
        .to_str()
        .ok_or("temporary project path must be valid UTF-8")?;
    let attrs_path = attrs_path
        .to_str()
        .ok_or("temporary attributes path must be valid UTF-8")?;
    let data = run(&[
        "--eval",
        "--strict",
        "--json",
        "-E",
        EXPRESSION,
        "--argstr",
        "nixpkgsPath",
        checkout,
        "--argstr",
        "projectPath",
        project,
        "--argstr",
        "system",
        system,
        "--argstr",
        "attributesPath",
        attrs_path,
    ])
    .map_err(|e| format!("target coverage evaluation failed: {e}"))?;
    let result: Evaluation =
        serde_json::from_str(&data).map_err(|e| format!("invalid target coverage result: {e}"))?;
    if !result.failed_assertions.is_empty() {
        return Err(format!(
            "target modules have {} failing assertions; coverage not applied",
            result.failed_assertions.len()
        ));
    }
    if result.results.len() != attrs.len() || attrs.iter().any(|a| !result.results.contains_key(a))
    {
        return Err("target coverage evaluation returned incomplete results".into());
    }
    let mut matched = BTreeMap::new();
    let mut unavailable_candidates = 0;
    for (attr, candidate) in result.results {
        match (candidate.state.as_str(), candidate.evidence) {
            ("matched", Some(evidence)) if valid_store_path(&evidence.path) => {
                matched.insert(attr, evidence);
            }
            ("not_matched", None) => {}
            ("unavailable", None) => unavailable_candidates += 1,
            _ => return Err("invalid target coverage evaluation result".into()),
        }
    }
    let evidence = Evidence {
        schema_version: 1,
        nixpkgs_revision: revision.into(),
        system: system.into(),
        candidate_count: attrs.len(),
        matched,
        unavailable_candidates,
        unavailable_system_packages: result.unavailable_system_packages,
    };
    validate(&evidence, revision, system, &decisions)?;
    Ok(evidence)
}
